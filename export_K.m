function export_K(K_K, py_dir, c_dir)
% EXPORT_K  把 LQR_K.m 拟合出的系数数组导出成 Python / C 两种源码文件。
%
% 用法:
%   export_K(K_K, py_dir, c_dir)
%   例: export_K(K_K, 'D:\proj\wheel_leg_mujoco', 'D:\proj\firmware\LQR')
%
% 输入:
%   K_K    4×10×6 三维数组 (控制量 × 状态量 × 系数项), 由 LQR_K.m 产生。
%          第 3 维顺序为 [常数, l_l, l_l^2, l_r, l_r^2, l_l*l_r]。
%          省略或为空时, 依次尝试调用者工作区的 K_K、本文件同目录的 LQR_K_coeff.mat。
%   py_dir Python 文件 LQR_K_coeff.py 的输出目录 (必填, 必须已存在)。
%   c_dir  C 文件 LQR_K_coeff.h 的输出目录 (必填, 必须已存在)。
%
% 输出:
%   py_dir/LQR_K_coeff.py    K_COEFF = np.stack([...], axis=0)      形状 (6,4,10)
%   c_dir/LQR_K_coeff.h      static const double K_COEFF[6][4][10]  元素顺序与上面相同
%
% 说明:
%   两个文件里的数字完全一样, 只是标点和括号按目标语言写:
%     Python 用方括号 [ ] , C 用花括号 { }。
%   MATLAB 本身不做语法转换, 全部靠 fprintf 按模板拼字符串完成。

%% ── K_K 缺省处理 ───────────────────────────────────────────
% MATLAB 不会自动把工作区里的同名变量当成参数传入: 直接敲 export_K 相当于
% "零个参数" 调用, 函数内部的 K_K 是空的, 与工作区无关。
% 这里做兼容: 先取调用者工作区的 K_K, 取不到再读本文件同目录的 LQR_K_coeff.mat。
if nargin < 1 || isempty(K_K)
    try
        K_K = evalin('base', 'K_K');       % 从 base 工作区按名字取值
    catch
        mf = fullfile(fileparts(mfilename('fullpath')), 'LQR_K_coeff.mat');
        if exist(mf, 'file') ~= 2
            error(['未传入 K_K, 工作区也没有 K_K, 且找不到 %s。' ...
                   '请改用 export_K(K_K) 显式传入。'], mf);
        end
        S = load(mf, 'K_K');               % load 返回结构体, 字段名即变量名
        K_K = S.K_K;
    end
end

%% ── 参数检查 ───────────────────────────────────────────────
% nargin < 3 时 c_dir 还没被创建, 必须最先判断, 否则引用它会报"输入参数不足"
if nargin < 3
    error('必须传入两个输出目录: export_K(K_K, py_dir, c_dir)');
end
if isempty(py_dir) || isempty(c_dir)
    error('py_dir / c_dir 不能为空');
end
if exist(py_dir, 'dir') ~= 7           % exist(...,'dir') 返回 7 表示"目录存在"
    error('Python 输出目录不存在: %s', py_dir);
end
if exist(c_dir, 'dir') ~= 7
    error('C 输出目录不存在: %s', c_dir);
end

% 维度校验: 防止把 (6,4,10) 之类顺序错误的数组传进来却仍写出乱序文件
if ~isequal(size(K_K), [4 10 6])
    error('K_K 维度应为 4×10×6 (控制量×状态量×系数项), 当前为 %s', mat2str(size(K_K)));
end

% permute(A,[3 1 2]): 重排维度顺序, 结果为 (第3维, 第1维, 第2维) = (6,4,10)
% 这样"系数项"成为第一维, 与 Python 里 np.stack 的堆叠方向、C 里 [6][4][10] 一一对应
Kp = permute(K_K, [3 1 2]);            % (6,4,10): 项 × 控制量 × 状态量

fmt = '%.6f, ';                        % 每个数字 6 位小数, 末尾带逗号+空格
                                       % 不用 %g: 它会输出 1e-05 这类科学计数, 后面校验时不好抓

name_py = {'常数项', 'l_l', 'l_l^2', 'l_r', 'l_r^2', 'l_l*l_r'};
name_c  = {'const',  'l_l', 'l_l^2', 'l_r', 'l_r^2', 'l_l*l_r'};
% C 侧注释用纯 ASCII: Keil C51 / ARMCC 对 UTF-8 中文注释可能直接报错

%% ── 打开两个文本文件 ───────────────────────────────────────
% fopen(文件名, 权限, 机器格式, 编码):
%   'wt' = 写 + 文本模式;  'n' = 本机字节序 (对文本无影响);
%   'UTF-8' 必须显式指定, 否则 MATLAB 会用系统默认编码(中文 Windows 是 GBK),
%   Python 3 默认按 UTF-8 读源码, 中文注释会直接 SyntaxError。
fid_py = fopen(fullfile(py_dir, 'LQR_K_coeff.py'), 'wt', 'n', 'UTF-8');
fid_h  = fopen(fullfile(c_dir,  'LQR_K_coeff.h'),  'wt', 'n', 'UTF-8');
if fid_py < 0 || fid_h < 0
    error('无法写入: %s 或 %s', py_dir, c_dir);
end

%% ── 文件头 ─────────────────────────────────────────────────
fprintf(fid_py, '# 由 sjtu-wl-lqr-matlab/export_K.m 自动生成, 请勿手改\n');
fprintf(fid_py, '# K(l_l,l_r) = sum_p K_COEFF[p] * basis[p]\n');
fprintf(fid_py, '# basis = [1, l_l, l_l^2, l_r, l_r^2, l_l*l_r]\n');
fprintf(fid_py, 'import numpy as np\n\n');
fprintf(fid_py, 'K_COEFF = np.stack([\n');

fprintf(fid_h,  '/* auto-generated by export_K.m, do not edit */\n');
fprintf(fid_h,  '/* K = sum_p K_COEFF[p][r][c] * basis[p] */\n');
fprintf(fid_h,  '/* basis = [1, l_l, l_l^2, l_r, l_r^2, l_l*l_r] */\n');
fprintf(fid_h,  'static const double K_COEFF[6][4][10] = {\n');

%% ── 主体: 6 页 × 4 行 × 10 列 ──────────────────────────────
% 每行、每页末尾都统一加一个逗号, 不判断"是否为最后一个":
%   Python 的 [1,2,] 与 C99 的 {1,2,} 都合法, 省掉所有分隔符判断逻辑。
for p = 1:6
    % p-1 是为了让注释里的编号与 Python/C 的 0 基下标一致
    fprintf(fid_py, '    # %d: %s\n    [\n', p-1, name_py{p});
    fprintf(fid_h,  '    /* %d: %s */\n    {\n', p-1, name_c{p});

    for r = 1:4
        % squeeze(Kp(p,r,:)): 把 1×1×10 去掉长度 1 的维度 → 10×1 列向量
        % sprintf(格式, 向量): 格式里只有一个转换符, 会按顺序循环消耗整个向量,
        %   于是 10 个数被拼成 "a, b, c, ..., j, " (末尾多一个 ", ")
        row = sprintf(fmt, squeeze(Kp(p,r,:)));
        % row(1:end-2): end 表示最后一个字符的下标, end-2 上界剪掉末尾的 ", " 两个字符
        row = row(1:end-2);
        fprintf(fid_py, '        [%s],\n', row);
        fprintf(fid_h,  '        { %s },\n', row);
    end

    fprintf(fid_py, '    ],\n');
    fprintf(fid_h,  '    },\n');
end

% 收尾: 关闭最外层括号
fprintf(fid_py, '], axis=0)   # shape = (6, 4, 10)\n');
fprintf(fid_h,  '};\n');

fclose(fid_py);
fclose(fid_h);

%% ── 回读校验 ───────────────────────────────────────────────
% 目的: 确认写出的数字没有丢位、没有错序。
% regexp: 用正则抓出所有 "小数", 因为格式化统一是 %.6f, 不存在指数形式, 可全部匹配
txt = fileread(fullfile(py_dir, 'LQR_K_coeff.py'));
val = str2double(regexp(txt, '-?\d+\.\d+', 'match'));   % 'match' = 返回匹配到的字符串元胞

% 按文件里的书写顺序 (p 外层 → r → c) 重建参考序列, 用于逐项比对
ref = zeros(1, 6*4*10);
k = 0;
for p = 1:6
    for r = 1:4
        for c = 1:10
            k = k + 1;
            ref(k) = Kp(p, r, c);
        end
    end
end

if numel(val) ~= numel(ref)
    error('回读数量不符: 解析到 %d 个, 期望 %d 个', numel(val), numel(ref));
end
fprintf('回读校验: %d 个数, 最大偏差 %.1e\n', numel(val), max(abs(val - ref)));
fprintf('已生成: %s\n        %s\n', ...
        fullfile(py_dir, 'LQR_K_coeff.py'), fullfile(c_dir, 'LQR_K_coeff.h'));
end
